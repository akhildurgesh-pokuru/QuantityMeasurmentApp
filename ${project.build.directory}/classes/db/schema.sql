
-- UC16: Main measurement operation table.
CREATE TABLE IF NOT EXISTS quantity_measurement_entity (

                                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                                           operation VARCHAR(40) NOT NULL,

    first_value DOUBLE PRECISION,
    first_type VARCHAR(40),
    first_unit VARCHAR(40),

    second_value DOUBLE PRECISION,
    second_type VARCHAR(40),
    second_unit VARCHAR(40),

    result_value DOUBLE PRECISION,
    result_type VARCHAR(40),
    result_unit VARCHAR(40),

    comparison_result BOOLEAN,
    scalar_result DOUBLE PRECISION,

    error_message VARCHAR(2000),

    created_at VARCHAR(80) NOT NULL
    );

-- Audit table for recording every saved operation.
CREATE TABLE IF NOT EXISTS quantity_measurement_history (

                                                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                                            measurement_id BIGINT NOT NULL,

                                                            operation VARCHAR(40) NOT NULL,

    recorded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT fk_measurement_history
    FOREIGN KEY (measurement_id)
    REFERENCES quantity_measurement_entity(id)
    ON DELETE CASCADE
    );

-- Improve queries filtered by operation name.
CREATE INDEX IF NOT EXISTS idx_measurement_operation
    ON quantity_measurement_entity(operation);

-- Improve queries filtered by measurement category.
CREATE INDEX IF NOT EXISTS idx_measurement_type
    ON quantity_measurement_entity(first_type);
